/* ─────────────────────────────────────────
   report.js — One-click printable system report
   (KPIs, live readings, energy, algae, impact) using a
   dedicated print window + print CSS. No dependencies.
───────────────────────────────────────── */
'use strict';

window.ALHYDRA = window.ALHYDRA || {};

ALHYDRA.report = (() => {

  function lang() { return ALHYDRA.i18n?.current?.() || 'en'; }
  function num(id) { const el = document.getElementById('val-' + id); if (!el) return '—'; return el.textContent || '—'; }

  function build() {
    const t = (en, id) => lang() === 'id' ? id : en;
    const now = new Date();
    const e = ALHYDRA.energy?.getState?.();
    const b = ALHYDRA.algae?.getBiomassEstimate?.();
    const user = window.auth?.currentUser?.email || '';
    const rows = [
      ['pH', num('ph')], ['Light (lux)', num('light')], ['Turbidity (NTU)', num('turbidity')],
      [t('Ambient °C', 'Suhu Ambient °C'), num('temp_ambient')], [t('Humidity %', 'Kelembaban %'), num('humidity')],
      [t('Water °C', 'Suhu Air °C'), num('temp_water')], [t('Water level %', 'Level air %'), num('water_level')],
      [t('Gen current A', 'Arus gen A'), num('current_gen')], [t('Cons current A', 'Arus kons A'), num('current_cons')],
    ];
    return `<!doctype html><html><head><meta charset="utf-8"><title>ALHYDRA Report</title>
      <style>
        *{box-sizing:border-box;font-family:Arial,Helvetica,sans-serif}
        body{margin:0;padding:40px;color:#0f172a}
        .head{display:flex;align-items:center;gap:14px;border-bottom:3px solid #10B981;padding-bottom:16px;margin-bottom:24px}
        .logo{width:48px;height:48px;border-radius:12px;background:linear-gradient(135deg,#10B981,#06B6D4);color:#fff;display:flex;align-items:center;justify-content:center;font-size:24px;font-weight:bold}
        h1{margin:0;font-size:22px} .sub{color:#64748b;font-size:12px}
        h2{font-size:15px;margin:24px 0 10px;color:#10B981;border-bottom:1px solid #e2e8f0;padding-bottom:6px}
        table{width:100%;border-collapse:collapse;font-size:13px}
        td,th{text-align:left;padding:8px 10px;border-bottom:1px solid #eef2f7}
        th{color:#64748b;font-weight:600}
        .kpis{display:flex;gap:14px;flex-wrap:wrap;margin-bottom:8px}
        .kpi{flex:1;min-width:120px;border:1px solid #e2e8f0;border-radius:10px;padding:12px}
        .kpi .v{font-size:22px;font-weight:800} .kpi .l{font-size:11px;color:#64748b}
        .foot{margin-top:36px;color:#94a3b8;font-size:11px;border-top:1px solid #e2e8f0;padding-top:12px}
        @media print{body{padding:16px}}
      </style></head><body>
      <div class="head"><div class="logo">🌿</div>
        <div><h1>ALHYDRA — ${t('System Report', 'Laporan Sistem')}</h1>
        <div class="sub">${now.toLocaleString()} · ${user}</div></div></div>

      <div class="kpis">
        <div class="kpi"><div class="v">${e ? e.soc + '%' : '—'}</div><div class="l">${t('Battery (SOC)', 'Baterai (SOC)')}</div></div>
        <div class="kpi"><div class="v">${e ? (e.balanceW >= 0 ? '+' : '') + e.balanceW + ' W' : '—'}</div><div class="l">${t('Energy balance', 'Keseimbangan energi')}</div></div>
        <div class="kpi"><div class="v">${e ? e.mode : '—'}</div><div class="l">${t('Energy mode', 'Mode energi')}</div></div>
        <div class="kpi"><div class="v">${b ? b.byCulture.length : 0}</div><div class="l">${t('Active cultures', 'Kultur aktif')}</div></div>
        <div class="kpi"><div class="v">${b ? b.kg.toFixed(2) + ' kg' : '0'}</div><div class="l">${t('Est. biomass', 'Est. biomassa')}</div></div>
      </div>

      <h2>${t('Live sensor readings', 'Pembacaan sensor langsung')}</h2>
      <table><thead><tr><th>${t('Parameter', 'Parameter')}</th><th>${t('Value', 'Nilai')}</th></tr></thead>
      <tbody>${rows.map(r => `<tr><td>${r[0]}</td><td><b>${r[1]}</b></td></tr>`).join('')}</tbody></table>

      <div class="foot">${t('Generated by ALHYDRA — Algae-Hydroponic Dual-Renewable Apparatus. Figures are decision-support estimates; verify with direct measurement.', 'Dihasilkan oleh ALHYDRA — Algae-Hydroponic Dual-Renewable Apparatus. Angka adalah estimasi pendukung keputusan; verifikasi dengan pengukuran langsung.')}<br>github.com/Mostoples/ALHYDRA</div>
      </body></html>`;
  }

  function print() {
    const w = window.open('', '_blank', 'width=900,height=700');
    if (!w) { ALHYDRA.app.toast(lang() === 'id' ? 'Izinkan pop-up untuk mencetak' : 'Allow pop-ups to print', 'warning'); return; }
    w.document.write(build());
    w.document.close();
    setTimeout(() => { try { w.focus(); w.print(); } catch (e) {} }, 400);
    ALHYDRA.audit?.log('report_print');
  }

  function init() {}
  return { init, print };
})();
